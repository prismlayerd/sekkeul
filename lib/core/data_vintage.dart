/// **이 빌드의 세법·복지 데이터가 언제 원문과 대조된 것인가.**
///
/// 앱은 온디바이스라 갱신 경로가 앱 업데이트뿐이다. 사용자는 지금 보고 있는
/// 금액이 언제 값인지 알 방법이 없고, 실제로 낡아 있었다 — 53개 제도 중
/// 21개가 옛 고시 값이었다(2026-08-02 전수 대조).
///
/// 업데이트 카드가 "새 버전이 있다"고 말할 때 **"지금 건 언제 것이다"**를 나란히
/// 보여주는 데 쓴다. 새것과 헌것이 같이 있을 때만 이 날짜가 뜻을 갖는다 —
/// 그래서 계산기 하단에는 안 넣는다(대조 직후엔 오늘 날짜라 알려주는 게 없다).
///
/// 갱신할 때: 카탈로그 **53개를 전부** 다시 대조한 날에만 [checkedOn]을 올린다.
class DataVintage {
  const DataVintage._();

  /// **카탈로그에서 가장 오래된 원문 대조일** (YYYY-MM-DD).
  ///
  /// 최신이 아니라 가장 오래된 쪽이다. 앱이 말하는 기준 시점은 제일 낡은
  /// 항목만큼만 진실이라서다 — 53개 중 12개만 다시 보고 이 값을 올리면
  /// 앱이 나머지 41개까지 그날 확인한 것처럼 말한다.
  /// 전수 대조를 끝낸 날에만 올라간다. `test/data_vintage_test.dart`가 지킨다.
  static const String checkedOn = '2026-09-08';

  /// "2026년 8월" — 사용자에게 보여줄 짧은 표기.
  static String get label {
    final p = checkedOn.split('-');
    return '${p[0]}년 ${int.parse(p[1])}월';
  }
}
